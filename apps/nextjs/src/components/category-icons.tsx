export function CategoryIcon({
  icon,
  className,
  ...props
}: { icon: string; className?: string } & SVGProps<SVGSVGElement>) {
  switch (icon.toLowerCase()) {
    case "meat":
    case "liha":
      return <MeatIcon className={className} {...props} />;
    case "fish":
    case "kala":
      return <FishIcon className={className} {...props} />;
    case "chicken":
    case "kana":
      return <ChickenIcon className={className} {...props} />;
    case "vegan":
    case "vege":
      return <VeganIcon className={className} {...props} />;
    case "kasvis":
      return <VegeIcon className={className} {...props} />;
    case "burger":
    case "burgeri":
      return <BurgerIcon className={className} {...props} />;
    case "pizza":
      return <PizzaIcon className={className} {...props} />;
    case "asian":
    case "aasialainen":
      return <AsianIcon className={className} {...props} />;
    case "texmex":
    case "tex-mex":
      return <TexMexIcon className={className} {...props} />;
    default:
      return <UtensilsIcon className={className} {...props} />;
  }
}
